function referencePath(ref) {
  if (!ref) return '';
  if (typeof ref.path === 'string') return ref.path;
  const path = ref._query?.path || ref._key?.path;
  if (path && typeof path.canonicalString === 'function') return path.canonicalString();
  if (Array.isArray(path?.segments)) return path.segments.join('/');
  return '';
}

// Wrap Firestore snapshots so the kiosk has one applicant subscription that
// other UI modules can reuse. This avoids duplicate websocket listeners and
// duplicate applicant snapshots on the Raspberry Pi.
export function onSnapshot(reference, ...args) {
  const path = referencePath(reference);

  // settings/mission is retained in older display code for compatibility, but
  // mission data now rides on an applicant document. Avoid a needless denied
  // listener/network request on the kiosk.
  if (isKiosk && path === 'settings/mission') return () => {};

  const callbackIndex = args.findIndex(arg => typeof arg === 'function');
  if (path === 'applicants' && callbackIndex >= 0 && typeof window !== 'undefined') {
    const original = args[callbackIndex];
    args[callbackIndex] = snapshot => {
      window.__PIBASE_APPLICANTS_SNAPSHOT__ = snapshot;
      window.dispatchEvent(new CustomEvent('pibase:applicants-snapshot', { detail: snapshot }));
      return original(snapshot);
    };
  }

  return firestoreOnSnapshot(reference, ...args);
}

